const MATCHERS = Object.fromEntries(
  Object.entries(RULES).map(([topic, words]) => [topic, makeMatcher(words)])
);

export function classify(text) {
  const hits = [];
  for (const [topic, match] of Object.entries(MATCHERS)) {
    const n = match(text || '').length;
    if (n) hits.push([topic, n]);
  }
  if (!hits.length) return ['general'];
  hits.sort((a, b) => b[1] - a[1]);
  const top = hits[0][1];
  // מחזיר את כל הנושאים עם לפחות חצי מהפגיעות של המוביל, עד 3
  return hits.filter(([, s]) => s >= Math.max(1, top / 2)).slice(0, 3).map(([t]) => t);
}
